/**
 * In-world game tests, runnable headless via {@code gradlew :RotaryCraft:runGameTest} or
 * interactively with {@code /test runall} (the {@code rotarycraft} namespace is enabled in
 * build.gradle). Each runs on the {@code rotarycraft:test_arena} structure — a 9×9×9
 * stone-floored box generated by {@link RoCTestStructureProvider}.
 *
 * <p>NeoForge 26.1's {@code RegisterGameTestsEvent} only registers {@link GameTestInstance}s,
 * and the vanilla {@code FunctionGameTestInstance} resolves its body through the
 * {@code TEST_FUNCTION} registry — which freezes before mod construction, so a mod can't add to
 * it. {@link DirectInstance} sidesteps that by holding the test body directly.</p>
 *
 * <p>The {@code TEST_INSTANCE} registry is network-synced (its entries are serialized to the
 * client during the login handshake), so {@link DirectInstance} must expose a real,
 * registry-backed {@link MapCodec} via {@link DirectInstance#codec()} — registered in
 * {@link #TEST_INSTANCE_TYPES}. The codec round-trips the serialisable {@link TestData}; the
 * decoded (client-side) instance carries a no-op body since clients never run the test.</p>
 */

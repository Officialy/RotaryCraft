    /**
     * A {@link GameTestInstance} that carries its test body as a plain {@link Consumer} instead of
     * a {@code TEST_FUNCTION} registry key. {@link #codec()} is never exercised because these are
     * registered as live objects (not serialized from a datapack) on the headless test server.
     */
    private static final class DirectInstance extends GameTestInstance {
        /**
         * Round-trips the serialisable {@link TestData}. Encoding reads the live instance's data;
         * decoding (only ever on a sync-receiving client) yields a no-op body — clients don't run
         * tests, they just need the registry entry to deserialise without crashing.
         */
        static final MapCodec<DirectInstance> CODEC =
                TestData.CODEC.xmap(data -> new DirectInstance(data, h -> {}), inst -> inst.info);

        private final TestData<Holder<TestEnvironmentDefinition<?>>> info;
        private final Consumer<GameTestHelper> body;

        DirectInstance(TestData<Holder<TestEnvironmentDefinition<?>>> info, Consumer<GameTestHelper> body) {
            super(info);
            this.info = info;
            this.body = body;
        }

        @Override
        public void run(GameTestHelper helper) {
            body.accept(helper);
        }

        @Override
        public MapCodec<? extends GameTestInstance> codec() {
            return CODEC;
        }

        @Override
        protected MutableComponent typeDescription() {
            return Component.literal("rotarycraft direct test");
        }
    }
